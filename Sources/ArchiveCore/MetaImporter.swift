import Foundation

public enum MetaService: String, Sendable, CaseIterable {
    case messenger, instagram

    var activityDir: String { self == .messenger ? "your_facebook_activity" : "your_instagram_activity" }
    var sourceKind: String { self == .messenger ? "messenger-thread" : "instagram-thread" }
    var exportKind: String { self == .messenger ? "messenger-export" : "instagram-export" }
    var nameOrigin: String { self == .messenger ? "messenger-export" : "instagram-export" }
    public var label: String { self == .messenger ? "Facebook Messenger" : "Instagram" }

    func handle(name: String, unique: String? = nil) -> ServiceHandle {
        self == .messenger ? .facebook(name: name, unique: unique) : .instagram(name: name, unique: unique)
    }
}

public struct MetaImportOptions: Sendable {
    /// The export owner's own display name. Detected when nil: Facebook's "Generated by <name>" header, else the name that appears in
    /// most threads.
    public var me: String?
    /// Instagram prints no offset anywhere; its times are wall-clock in a fixed -08:00 (calibrated against real exports).
    public var instagramOffsetSeconds = -8 * 3600
    /// Used for a Facebook page whose header carries no "UTC+hh:mm".
    public var fallbackZone = LocalZone.current().identifier
    /// A named zone (with DST) that replaces the page header's fixed offset for Facebook pages. Some exports' header says
    /// "UTC-05:00" (the offset on the day it was made) but prints every time in US Eastern wall clock with DST (measured against another
    /// export of the same account: exactly 3600 s apart from the March to the November change, equal in winter).
    public var facebookZone: String?
    public init(me: String? = nil) { self.me = me }
}

public struct MetaImportStats: Codable, Equatable, Sendable {
    public var threadFolders = 0
    public var foldersImported = 0
    public var foldersSkipped = 0           // already imported (same folder hash)
    public var files = 0
    public var blocks = 0                   // message blocks parsed
    public var inserted = 0                 // canonical rows written
    public var duplicates = 0               // rows linked to an earlier copy (kept for provenance)
    public var repeatedAcrossFiles = 0      // identical blocks repeated by a later message_N file, dropped
    public var system = 0, calls = 0, unsent = 0
    public var reactions = 0
    public var systemLinesTranslated = 0    // Instagram system lines the export wrote in Burmese, stored as English notes
    public var systemLinesFallback = 0      // Burmese lines not in the table (the last-resort rule); a new string shows up here
    public var emojiOnly = 0                // messages that were only emoji drawn as images (kept as a system note)
    public var attachments = 0
    public var mediaMissing = 0
    public var mediaBytes = 0               // bytes of attachment payloads referenced
    public var mediaNewBytes = 0, mediaNewFiles = 0
    public var emptySkipped = 0             // blocks with no text, media, link or call detail (removed content)
    public var badDate = 0
    public var unattributed = 0             // messages from a label-less sender that could not be named
    public var firstTsMs: Int64?, lastTsMs: Int64?
    public var inversions = 0               // chronological order violations after reversing the pages (sanity)
    public var seconds = 0.0
    public var foldersByOrigin: [String: Int] = [:]
    public var messagesByOrigin: [String: Int] = [:]
    public var hiddenThreads = 0
}

public struct MetaImportReport: Sendable {
    public enum Status: Sendable { case imported, alreadyImported }
    public var status: Status
    public var service: MetaService
    public var me: String?
    public var stats: MetaImportStats
    /// Instagram only: the usernames resolved at the end of the import (nil for Messenger, or when resolution failed, see `usernameError`).
    public var usernames: InstagramUsernames.Report?
    public var usernameError: String?
}

public struct MetaImportProgress: Sendable {
    public var foldersDone: Int
    public var foldersTotal: Int
    public var messages: Int
}

public enum MetaImporter {
    /// Thread-folder categories in precedence order (best first). `hidden` ones are not shown by default.
    static let categories: [(dir: String, origin: String, hidden: Bool)] = [
        ("inbox", "inbox", false), ("archived_threads", "archived", false), ("e2ee_cutover", "e2ee", false),
        ("filtered_threads", "filtered", true), ("message_requests", "requests", true),
    ]
    static func originRank(_ o: String?) -> Int { categories.firstIndex(where: { $0.origin == o }) ?? 99 }

    // MARK: detection

    /// Is `url` a Meta export (its root, or a folder holding one)? Returns the export root and its service.
    public static func detect(_ url: URL) -> (root: URL, service: MetaService)? {
        let fm = FileManager.default
        for s in MetaService.allCases where fm.fileExists(atPath: url.appendingPathComponent("\(s.activityDir)/messages").path) {
            return (url, s)
        }
        return nil
    }

    /// `url` itself, or the export folders one level below it.
    public static func detectAll(_ url: URL) -> [(root: URL, service: MetaService)] {
        if let d = detect(url) { return [d] }
        let kids = ((try? FileManager.default.contentsOfDirectory(at: url, includingPropertiesForKeys: [.isDirectoryKey])) ?? [])
            .sorted { $0.lastPathComponent < $1.lastPathComponent }
        return kids.compactMap { detect($0) }
    }

    // MARK: thread folders

    struct ThreadFolder {
        var category: (dir: String, origin: String, hidden: Bool)
        var name: String
        var url: URL
        var files: [URL]            // message_1.html, message_2.html, ... (newest page first)
        var externalID: String { String(name.split(separator: "_", omittingEmptySubsequences: true).last ?? Substring(name)) }
    }

    static func enumerate(service: MetaService, exportRoot: URL) -> [ThreadFolder] {
        let fm = FileManager.default
        let messages = exportRoot.appendingPathComponent("\(service.activityDir)/messages")
        var out: [ThreadFolder] = []
        for cat in categories {
            let dir = messages.appendingPathComponent(cat.dir)
            guard let kids = try? fm.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.isDirectoryKey]) else { continue }
            for k in kids.sorted(by: { $0.lastPathComponent < $1.lastPathComponent }) {
                guard (try? k.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true else { continue }
                let files = ((try? fm.contentsOfDirectory(at: k, includingPropertiesForKeys: nil)) ?? [])
                    .compactMap { u -> (Int, URL)? in
                        let n = u.lastPathComponent
                        guard n.hasPrefix("message_"), n.hasSuffix(".html"), let i = Int(n.dropFirst(8).dropLast(5)) else { return nil }
                        return (i, u)
                    }
                    .sorted { $0.0 < $1.0 }.map { $0.1 }
                if !files.isEmpty { out.append(ThreadFolder(category: cat, name: k.lastPathComponent, url: k, files: files)) }
            }
        }
        return out
    }

    // MARK: import

    public static func importExport(at exportRoot: URL, service: MetaService, into db: Database, root: ArchiveRoot,
                                    options: MetaImportOptions = MetaImportOptions(), origin: String? = nil,
                                    progress: ((MetaImportProgress) -> Void)? = nil) throws -> MetaImportReport {
        let t0 = Date()
        var stats = MetaImportStats()
        let folders = enumerate(service: service, exportRoot: exportRoot)
        stats.threadFolders = folders.count

        // Folder hashes: the hash of its page files plus identity, so an unchanged thread is never imported twice and a
        // changed one (a newer export with more messages) is imported again, its overlap linked as duplicates.
        var hashes: [String] = []
        var bytesByFolder: [Int64] = []
        for f in folders {
            var h = "meta-thread-v1|\(service.rawValue)|\(f.name)\n"
            var total: Int64 = 0
            for u in f.files {
                let (hex, n) = try Hashing.sha256Hex(ofFile: u)
                h += "\(u.lastPathComponent):\(hex)\n"
                total += n
            }
            hashes.append(sha256(of: h)); bytesByFolder.append(total)
        }
        let exportHash = sha256(of: "meta-export-v1|\(service.rawValue)|" + hashes.sorted().joined(separator: ","))
        let sel = try db.prepare("SELECT stats_json FROM source WHERE sha256 = ?")
        sel.bind(1, exportHash)
        if try sel.step() {
            let st = sel.string(0).flatMap { try? JSONDecoder().decode(MetaImportStats.self, from: Data($0.utf8)) } ?? MetaImportStats()
            sel.reset()
            return MetaImportReport(status: .alreadyImported, service: service, me: try metaValue(db, "\(service.rawValue).me"), stats: st)
        }
        sel.reset()

        let me = try detectMe(service: service, folders: folders, options: options)
        try setMeta(db, "\(service.rawValue).me", me)
        try setMeta(db, "\(service.rawValue).time_rule", service == .instagram
            ? "fixed UTC\(offsetString(options.instagramOffsetSeconds))"
            : options.facebookZone.map { "named zone \($0) with DST (--fb-zone, latest Facebook import); earlier exports: page header UTC offset" }
                ?? "page header UTC offset, else \(options.fallbackZone)")

        let store = MediaStore(root: root)
        let ctx = Context(service: service, exportRoot: exportRoot, me: me, meFold: ServiceHandle.foldName(me), options: options, store: store)
        let existing = try db.prepare("SELECT 1 FROM source WHERE sha256 = ?")
        var messages = 0
        for (i, f) in folders.enumerated() {
            existing.bind(1, hashes[i])
            let have = try existing.step()
            existing.reset()
            stats.foldersByOrigin[f.category.origin, default: 0] += 1
            if have { stats.foldersSkipped += 1; progress?(MetaImportProgress(foldersDone: i + 1, foldersTotal: folders.count, messages: messages)); continue }
            try db.transaction {
                try importFolder(f, hash: hashes[i], bytes: bytesByFolder[i], ctx: ctx, db: db, stats: &stats)
            }
            stats.foldersImported += 1
            messages = stats.inserted + stats.duplicates
            progress?(MetaImportProgress(foldersDone: i + 1, foldersTotal: folders.count, messages: messages))
        }
        stats.seconds = Date().timeIntervalSince(t0)
        stats.hiddenThreads = Int(try db.scalarInt("SELECT count(*) FROM thread WHERE hidden = 1 AND service = '\(service.rawValue)'"))
        let ins = try db.prepare("INSERT INTO source(kind, path, sha256, bytes, imported_at, stats_json) VALUES (?,?,?,?,?,?)")
        ins.bind(1, service.exportKind).bind(2, origin ?? exportRoot.path).bind(3, exportHash)
            .bind(4, bytesByFolder.reduce(0, +)).bind(5, Int64(Date().timeIntervalSince1970))
            .bind(6, String(decoding: try JSONEncoder().encode(stats), as: UTF8.self))
        try ins.run()
        var report = MetaImportReport(status: .imported, service: service, me: me, stats: stats)
        if service == .instagram {
            do { report.usernames = try InstagramUsernames.apply(exportRoot: exportRoot, into: db, me: me) }
            catch { report.usernameError = "\(error)" }
        }
        return report
    }

    // MARK: me

    static func detectMe(service: MetaService, folders: [ThreadFolder], options: MetaImportOptions) throws -> String {
        if let m = options.me?.trimmingCharacters(in: .whitespacesAndNewlines), !m.isEmpty { return m }
        var perThread: [String: (name: String, threads: Int)] = [:]
        var generated: [String: Int] = [:]
        for f in folders {
            guard let first = f.files.first, let data = try? Data(contentsOf: first, options: .alwaysMapped) else { continue }
            let page = MetaFileParser.parse(prefix: data, bytes: 96 << 10)
            if let g = MetaTime.generatedBy(inHeader: page.header) { generated[g, default: 0] += 1 }
            var seen = Set<String>()
            for b in page.blocks { if let s = b.sender { seen.insert(ServiceHandle.foldName(s)); if perThread[ServiceHandle.foldName(s)] == nil { perThread[ServiceHandle.foldName(s)] = (s, 0) } } }
            for k in seen { perThread[k]!.threads += 1 }
        }
        if let g = generated.max(by: { $0.value < $1.value })?.key { return g }
        if let best = perThread.values.max(by: { $0.threads < $1.threads }), folders.count >= 2, best.threads * 2 > folders.count { return best.name }
        throw ArchiveError("cannot tell which \(service.label) participant is you (no \"Generated by\" header and no name common to most threads); pass --me \"<your display name>\"")
    }

    // MARK: one thread folder

    final class Context {
        let service: MetaService, exportRoot: URL, me: String, meFold: String, options: MetaImportOptions, store: MediaStore
        var mediaCache: [String: AttachmentRecord?] = [:]
        init(service: MetaService, exportRoot: URL, me: String, meFold: String, options: MetaImportOptions, store: MediaStore) {
            self.service = service; self.exportRoot = exportRoot; self.me = me; self.meFold = meFold; self.options = options; self.store = store
        }
    }

    /// One emitted message before it is written.
    struct Pending {
        var tsMs: Int64
        var senderFold: String?          // nil = label-less
        var isMe: Bool
        var body: String?
        var kind: String?
        var note: String?
        var media: [MetaMediaRef]
        var reactions: [(emoji: String, name: String)]
    }

    /// The people in a thread other than me, in order: speakers, then the listed participants, then (for a one-person thread
    /// with no speaker) the title, else "Unknown". Shared by the importer and the Instagram username resolver so both name a
    /// thread's people identically.
    static func determineOthers(labels: [String: String], labelOrder: [String], participantNames: [String], title: String, meFold: String)
        -> (others: [(fold: String, name: String)], titleIsList: Bool) {
        var others: [(fold: String, name: String)] = []
        func addOther(_ name: String) {
            let k = ServiceHandle.foldName(name)
            if k == meFold || k.isEmpty || others.contains(where: { $0.fold == k }) { return }
            others.append((k, name))
        }
        for k in labelOrder { addOther(labels[k]!) }
        for n in participantNames { addOther(n) }
        let titleIsList = title.hasPrefix("Participants:")
        if titleIsList, let list = participantList(title) { for n in list { addOther(n) } }
        if others.isEmpty, !title.isEmpty, !titleIsList { addOther(title) }
        if others.isEmpty { addOther("Unknown") }
        return (others, titleIsList)
    }

    static func importFolder(_ f: ThreadFolder, hash: String, bytes: Int64, ctx: Context, db: Database, stats: inout MetaImportStats) throws {
        let service = ctx.service
        let ins = try db.prepare("INSERT INTO source(kind, path, sha256, bytes, imported_at, stats_json) VALUES (?,?,?,?,?,NULL)")
        ins.bind(1, service.sourceKind).bind(2, f.url.path).bind(3, hash).bind(4, bytes).bind(5, Int64(Date().timeIntervalSince1970))
        try ins.run()
        let sid = db.lastInsertRowID

        // Parse every page, newest first; collect names.
        var pages: [(file: MetaFile, zone: MetaTime.Zone)] = []
        var title = ""
        var labels: [String: String] = [:]          // fold -> display
        var labelOrder: [String] = []
        var participantNames: [String] = []
        for u in f.files {
            let data = try Data(contentsOf: u, options: .alwaysMapped)
            let page = MetaFileParser.parse(data: data)
            stats.files += 1
            if title.isEmpty { title = page.title.trimmingCharacters(in: .whitespacesAndNewlines) }
            let zone: MetaTime.Zone
            if service == .instagram { zone = .fixed(seconds: ctx.options.instagramOffsetSeconds) }
            else if let z = ctx.options.facebookZone { zone = .named(z) }
            else if let off = MetaTime.offset(inHeader: page.header) { zone = .fixed(seconds: off) }
            else { zone = .named(ctx.options.fallbackZone) }
            for b in page.blocks {
                if let s = b.sender {
                    let k = ServiceHandle.foldName(s)
                    if labels[k] == nil { labels[k] = s; labelOrder.append(k) }
                }
                if let l = b.labelOnly, let list = participantList(l) {
                    for n in list where !participantNames.contains(where: { ServiceHandle.foldName($0) == ServiceHandle.foldName(n) }) { participantNames.append(n) }
                }
            }
            pages.append((page, zone))
        }

        // People in the thread, never including me. A deactivated account's name ("Facebook user") is per-thread, not global.
        let ext = f.externalID
        func person(_ name: String) -> ServiceHandle {
            let k = ServiceHandle.foldName(name)
            let placeholder = k == "facebook user" || k == "instagram user" || k == "unknown"
            return service.handle(name: name, unique: placeholder ? ext : nil)
        }
        let (others, titleIsList) = determineOthers(labels: labels, labelOrder: labelOrder, participantNames: participantNames, title: title, meFold: ctx.meFold)
        // A label-less sender is the one listed participant nobody has spoken as, when exactly one is left.
        let spoken = Set(labelOrder)
        let silent = others.filter { !spoken.contains($0.fold) }
        let unlabelled: (fold: String, name: String)? = silent.count == 1 ? silent[0] : nil

        // Chronological messages: pages run newest -> oldest and each page newest -> oldest, so reverse both.
        var pending: [Pending] = []
        var lastTs = Int64.min
        var global: [String: Int] = [:]
        for (page, zone) in pages.reversed() {
            var local: [String: Int] = [:]
            for b in page.blocks.reversed() {
                if b.timeText.isEmpty { continue }            // the participants line, "Mailbox thread", group-invite links: no time, no message
                stats.blocks += 1
                guard let civil = MetaTime.parse(b.timeText), let ts = MetaTime.unixMs(civil, zone: zone) else { stats.badDate += 1; continue }
                let senderFold = b.sender.map { ServiceHandle.foldName($0) }
                let isMe = senderFold == ctx.meFold
                var p = Pending(tsMs: ts, senderFold: senderFold, isMe: isMe, body: nil, kind: nil, note: nil, media: b.media, reactions: b.reactions)
                if let t = classify(b, senderLabel: b.sender, isMe: isMe, into: &p) { if t.fallback { stats.systemLinesFallback += 1 } else { stats.systemLinesTranslated += 1 } }
                if p.body == nil && p.kind == nil && p.media.isEmpty {
                    if !b.emojiImages.isEmpty {
                        p.kind = "system"
                        p.note = "(emoji image not in export) " + b.emojiImages.map { emojiRef($0) }.joined(separator: " ")
                        stats.emojiOnly += 1
                    }
                    else { stats.emptySkipped += 1; continue }
                }
                // Repeats across pages (a later page restating messages): keep the larger multiplicity, not the sum.
                let key = "\(ts)|\(senderFold ?? "")|\(p.body ?? "")|\(p.note ?? "")|\(p.media.map { $0.path }.joined(separator: ","))"
                local[key, default: 0] += 1
                if local[key]! <= (global[key] ?? 0) { stats.repeatedAcrossFiles += 1; continue }
                pending.append(p)
            }
            for (k, v) in local { global[k] = max(global[k] ?? 0, v) }
        }
        for p in pending { if p.tsMs < lastTs { stats.inversions += 1 }; lastTs = max(lastTs, p.tsMs) }

        // Write.
        let writer = try ArchiveWriter(db: db, sourceID: sid, sourceKind: service.sourceKind)
        writer.groupKeySuffix = ext
        writer.groupExternalService = service.rawValue
        let participantHandles = others.map { person($0.name) }
        var threadID: Int64?
        var inserted = 0, duplicates = 0
        for p in pending {
            var rec = MessageRecord(participants: [], sender: nil, tsMs: p.tsMs, isFromMe: p.isMe, service: service.rawValue,
                                    body: p.body, subject: nil, sourceKey: nil, attachments: [])
            rec.participantHandles = participantHandles
            if !p.isMe {
                if let k = p.senderFold, let name = labels[k] { rec.senderHandle = person(name) }
                else if let u = unlabelled { rec.senderHandle = person(u.name) }
                else { stats.unattributed += 1 }
            }
            rec.kind = p.kind; rec.note = p.note
            switch p.kind { case "system"?: stats.system += 1; case "call"?: stats.calls += 1; case "unsent"?: stats.unsent += 1; default: break }
            for m in p.media {
                if let a = try attachment(for: m, ctx: ctx, writer: writer, stats: &stats) { rec.attachments.append(a); stats.attachments += 1 }
            }
            // A pure attachment marker whose media never made it into the export stays as a system line, so the gap is visible.
            if rec.body == nil, rec.kind == nil, rec.attachments.isEmpty { rec.kind = "system"; rec.note = "(attachment not in export)"; stats.system += 1 }
            for r in p.reactions {
                let k = ServiceHandle.foldName(r.name)
                if k == ctx.meFold { rec.reactions.append(ReactionRecord(emoji: r.emoji, actor: nil, byMe: true)) }
                else { rec.reactions.append(ReactionRecord(emoji: r.emoji, actor: person(r.name), byMe: false)) }
                stats.reactions += 1
            }
            switch try writer.add(rec) {
            case .inserted: inserted += 1
            case .duplicate: duplicates += 1
            }
            threadID = writer.lastThreadID
        }
        stats.inserted += inserted; stats.duplicates += duplicates
        stats.messagesByOrigin[f.category.origin, default: 0] += inserted
        if let a = pending.first?.tsMs { stats.firstTsMs = min(stats.firstTsMs ?? a, a) }
        if let b = pending.last?.tsMs { stats.lastTsMs = max(stats.lastTsMs ?? b, b) }

        // Names for the people (the display name). A real Instagram username is never read from the folder name (it is the
        // lowercased display name, not a handle); `InstagramUsernames` resolves usernames from the export's follower lists.
        for o in others {
            try writer.noteName(service: person(o.name), name: o.name, origin: service.nameOrigin, priority: ContactPriority.androidXML)
        }

        // Thread flags: where it came from, hidden-by-default for filtered threads and requests, a custom group name.
        if let tid = threadID {
            let sel = try db.prepare("SELECT origin, hidden, title, is_group FROM thread WHERE id = ?")
            sel.bind(1, tid)
            _ = try sel.step()
            let oldOrigin = sel.string(0), oldTitle = sel.string(2), isGroup = sel.int(3) != 0
            sel.reset()
            let better = originRank(f.category.origin) < originRank(oldOrigin)
            let origin = better ? f.category.origin : (oldOrigin ?? f.category.origin)
            let hidden = categories.first(where: { $0.origin == origin })?.hidden ?? false
            let newTitle = (oldTitle == nil && isGroup && !title.isEmpty && !titleIsList) ? title : oldTitle
            let up = try db.prepare("UPDATE thread SET service = ?, origin = ?, hidden = ?, external_id = COALESCE(external_id, ?), title = ? WHERE id = ?")
            up.bind(1, service.rawValue).bind(2, origin).bind(3, hidden).bind(4, ext).bind(5, newTitle).bind(6, tid)
            try up.run()
        }

        var s = MetaImportStats()
        s.files = f.files.count; s.inserted = inserted; s.duplicates = duplicates
        let up = try db.prepare("UPDATE source SET stats_json = ? WHERE id = ?")
        up.bind(1, String(decoding: try JSONEncoder().encode(s), as: UTF8.self)).bind(2, sid)
        try up.run()
    }

    // MARK: block -> message

    /// The file name of an emoji image's URL (query string dropped), enough to map it to an emoji later.
    static func emojiRef(_ url: String) -> String {
        let path = url.split(separator: "?", maxSplits: 1).first.map(String.init) ?? url
        return path.split(separator: "/").last.map(String.init) ?? path
    }

    static func participantList(_ line: String) -> [String]? {
        guard line.hasPrefix("Participants:") else { return nil }
        let rest = line.dropFirst("Participants:".count).trimmingCharacters(in: .whitespaces)
        var parts = rest.components(separatedBy: ", ")
        if var last = parts.popLast() {
            if let r = last.range(of: " and ", options: .backwards) {
                parts.append(String(last[last.startIndex..<r.lowerBound]))
                last = String(last[r.upperBound...])
            }
            parts.append(last)
        }
        return parts.map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
    }

    static let callPhrases = ["video call ended", "missed a video call", "missed your video call", "missed a call", "missed your call",
                              "called ", "started a video call", "joined the video call", "started a call", "joined the call",
                              "ended the call", "call ended", "started an audio call", "missed an audio call"]
    static let systemPhrases = ["added ", "removed ", "left the group", "left the conversation", "named the group", "changed the group",
                                "changed the theme", "changed the chat", "changed the nickname", "set the nickname", "set nickname",
                                "cleared the nickname", "created the group", "joined the group", "joined the conversation",
                                "turned on", "turned off", "waved", "changed their", "updated the group", "changed your", "set the emoji",
                                "changed the emoji", "pinned a message", "unpinned a message"]
    static let markerSuffixes = [" sent an attachment.", " sent a link.", " shared a story.", " sent a sticker.", " sent a voice message.",
                                 " sent a photo.", " sent a video.", " shared a reel.", " shared a post.", " sent a gif."]

    static func phraseNearStart(_ text: String, _ phrase: String) -> Bool {
        let words = text.split(separator: " ", maxSplits: 4, omittingEmptySubsequences: true)
        guard words.count > 1 else { return false }
        // the actor is one to three words ("You", "Alice", "Alice Example"); the phrase follows immediately
        for n in 1...min(3, words.count - 1) {
            let rest = words[n...].joined(separator: " ") + " "
            if rest.hasPrefix(phrase) { return true }
        }
        return false
    }

    /// Decides what the block is: text, a placeholder marker for media or a link, a system line, a call or an unsent message.
    @discardableResult
    static func classify(_ b: MetaBlock, senderLabel: String?, isMe: Bool = false, into p: inout Pending) -> InstagramSystemLines.Result? {
        var text = b.text
        if let t = InstagramSystemLines.translate(text, actor: senderLabel, isMe: isMe) {
            p.kind = t.kind
            p.note = b.callDetail.map { t.note + " (" + $0 + ")" } ?? t.note
            return t
        }
        var links = b.shareLinks
        let isMarker = markerSuffixes.contains(where: { text.hasSuffix($0) && !text.contains("\n") })
        if isMarker {
            // The placeholder says "X sent an attachment." / "X sent a link."; the real content is the media or the link.
            if !b.media.isEmpty || !links.isEmpty || !b.emojiImages.isEmpty { text = "" }
            else { p.kind = "system"; p.note = text; return nil }
        }
        if !text.isEmpty, text.count < 220, !text.contains("\n") {
            if text.contains("message was unsent") || text.contains("unsent a message") || text.contains("was unsent by the sender")
                || text.contains("has been unsent") {
                p.kind = "unsent"; p.note = text; return nil
            }
            let prefixOK: Bool = {
                if text.hasPrefix("A contact ") || text.hasPrefix("You ") { return true }
                if let s = senderLabel, text.hasPrefix(s + " ") { return true }
                if senderLabel == nil, let f = text.first, f.isUppercase { return true }
                return false
            }()
            if prefixOK, text.hasSuffix(".") {
                if callPhrases.contains(where: { text.contains(" " + $0) || text.hasPrefix($0) }) {
                    p.kind = "call"; p.note = b.callDetail.map { text + " (" + $0 + ")" } ?? text; return nil
                }
                if systemPhrases.contains(where: { text.contains(" " + $0) }) {
                    // "You ..." and label-less text are only system lines when the phrase sits right after the actor
                    // (first or second word); a sentence that merely mentions "added " later on stays a message.
                    let strict = !(text.hasPrefix("A contact ") || senderLabel.map { text.hasPrefix($0 + " ") } == true)
                    if !strict || systemPhrases.contains(where: { phraseNearStart(text, $0) }) { p.kind = "system"; p.note = text; return nil }
                }
            }
        }
        if let d = b.callDetail, p.kind == nil {
            // a call row whose wording we did not recognize still carries its duration
            p.kind = "call"; p.note = text.isEmpty ? d : text + " (" + d + ")"; return nil
        }
        links.removeAll { text.contains($0) }
        var body = text
        for l in links { body += (body.isEmpty ? "" : "\n") + l }
        p.body = body.isEmpty ? nil : body
        return nil
    }

    // MARK: media

    static let mimeByExtension: [String: String] = [
        "jpg": "image/jpeg", "jpeg": "image/jpeg", "png": "image/png", "gif": "image/gif", "webp": "image/webp", "heic": "image/heic",
        "mp4": "video/mp4", "mov": "video/quicktime", "m4v": "video/mp4", "3gp": "video/3gpp", "webm": "video/webm",
        "mp3": "audio/mpeg", "m4a": "audio/mp4", "aac": "audio/aac", "wav": "audio/x-wav", "ogg": "audio/ogg", "amr": "audio/amr", "opus": "audio/ogg",
        "pdf": "application/pdf", "txt": "text/plain", "vcf": "text/vcard",
    ]

    static func attachment(for m: MetaMediaRef, ctx: Context, writer: ArchiveWriter, stats: inout MetaImportStats) throws -> AttachmentRecord? {
        if let cached = ctx.mediaCache[m.path] {
            if let c = cached { stats.mediaBytes += c.bytes }
            return cached
        }
        func miss() -> AttachmentRecord? { ctx.mediaCache[m.path] = .some(nil); stats.mediaMissing += 1; return nil }
        // Only files inside the export root (posts and stories live beside messages); never an escape out of it.
        let comps = m.path.split(separator: "/").map(String.init)
        guard !m.path.hasPrefix("/"), !comps.contains(".."), !comps.contains("."), comps.count >= 2 else { return miss() }
        let url = ctx.exportRoot.appendingPathComponent(m.path)
        guard let data = try? Data(contentsOf: url, options: .alwaysMapped) else { return miss() }
        let ext = (m.path as NSString).pathExtension.lowercased()
        let mime = mimeByExtension[ext] ?? (m.kind == .image ? "image/jpeg" : nil)
        let filename = (m.path as NSString).lastPathComponent
        let stored = try data.withUnsafeBytes { raw in
            try ctx.store.store(raw, mime: mime, filename: filename, lookup: { writer.existingMediaPath(sha256: $0) })
        }
        if stored.wasNew { stats.mediaNewFiles += 1; stats.mediaNewBytes += stored.bytes }
        stats.mediaBytes += stored.bytes
        let rec = AttachmentRecord(mime: mime, filename: filename, sha256: stored.sha256, relativePath: stored.relativePath, bytes: stored.bytes)
        ctx.mediaCache[m.path] = .some(rec)
        return rec
    }

    // MARK: helpers

    static func sha256(of s: String) -> String { var s = s; return s.withUTF8 { Hashing.sha256Hex(UnsafeRawBufferPointer($0)) } }

    static func offsetString(_ secs: Int) -> String {
        (secs < 0 ? "-" : "+") + String(format: "%02d:%02d", abs(secs) / 3600, abs(secs) % 3600 / 60)
    }

    static func metaValue(_ db: Database, _ key: String) throws -> String? {
        let st = try db.prepare("SELECT value FROM meta WHERE key = ?")
        st.bind(1, key)
        defer { st.reset() }
        return try st.step() ? st.string(0) : nil
    }

    static func setMeta(_ db: Database, _ key: String, _ value: String) throws {
        let st = try db.prepare("INSERT INTO meta(key, value) VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value = excluded.value")
        st.bind(1, key).bind(2, value)
        try st.run()
    }
