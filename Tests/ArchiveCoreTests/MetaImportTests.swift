        #expect(try db.scalarInt("SELECT service IS NULL AND origin IS NULL AND external_id IS NULL FROM thread") == 1)
        #expect(try db.scalarInt("SELECT count(*) FROM reaction") == 0)
        #expect(try db.scalarInt("SELECT count(*) FROM message_fts WHERE message_fts MATCH 'old'") == 1)
