    @Test func scannerSkipsCommentsDoctypeStyleAndReadsOddAttributes() {
        final class Rec: HTMLScannerDelegate {
            var events: [String] = []
            func startTag(_ tag: HTMLTag, attrs: HTMLAttrs, selfClosing: Bool) {
                events.append("<\(tag)\(selfClosing ? "/" : "") src=\(attrs.src.map { HTMLEntities.decode($0) } ?? "-") cls=\(attrs.cls.map { String(decoding: $0, as: UTF8.self) } ?? "-")>")
            }
            func endTag(_ tag: HTMLTag) { events.append("</\(tag)>") }
            func text(_ bytes: UnsafeBufferPointer<UInt8>) { events.append("T:" + HTMLEntities.decode(bytes)) }
        }
        let html = "<!DOCTYPE html><!-- <div>hidden</div> --><style>div > p { color: red }</style><DIV CLASS=x src=a&amp;b>hi<br><img src='q.jpg' /></DIV>"
        let r = Rec()
        Array(html.utf8).withUnsafeBufferPointer { HTMLScanner.scan($0, delegate: r) }
        #expect(r.events == ["<style src=- cls=->", "</style>", "<div src=a&b cls=x>", "T:hi", "<br/ src=- cls=->", "<img/ src=q.jpg cls=->", "</div>"])
    }

    @Test func aTruncatedPageStillDeliversTheBlocksItHolds() {
        let page = MetaFixtures.fbPage(title: "Alice Example", [
            .init(sender: "Alice Example", text: "complete", time: "Jan 05, 2019 3:22:15 pm"),
            .init(sender: "Alice Example", text: "cut off here", time: "Jan 05, 2019 3:22:16 pm"),
        ])
        let cut = String(page.prefix(upTo: page.range(of: "cut off here")!.upperBound))
        let f = MetaFileParser.parse(prefix: Data(cut.utf8), bytes: cut.utf8.count)
        #expect(f.blocks.count == 2 && f.blocks[0].text == "complete" && f.blocks[1].text == "cut off here")
    }

    @Test func toleratesMalformedHtml() {
        // unclosed tags, stray '<', an unterminated comment-ish, uppercase tags
        let page = "<html><body><DIV class=\"_a6-g\"><div class=\"_2ph_ _a6-h _a6-i\">A B<div class=\"_2ph_ _a6-p\"><div><div></div><div>1 < 2 and x</div></div></div><div class=\"_3-94 _a6-o\">Jan 05, 2019 3:22:15 pm</div></DIV><!-- never closed"
        let f = MetaFileParser.parse(data: Data(page.utf8))
        #expect(f.blocks.count >= 1)
    }
}

