            #expect(throws: (any Error).self) { try db.exec("SELECT kind FROM message") }      // v4 has no such column
        }
        let db = try Schema.openArchive(root: root)                                          // the app/CLI path: migrates on open
        #expect(try db.userVersion() == Schema.currentVersion && Schema.currentVersion >= 5)
