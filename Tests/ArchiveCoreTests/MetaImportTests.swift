@Suite struct MetaTimeTests {
    @Test func fixedOffsetFromHeader() {
        let c = MetaTime.parse("Jan 05, 2019 3:22:15 pm")!
        #expect(c == MetaTime.Civil(y: 2019, mo: 1, d: 5, h: 15, mi: 22, s: 15))
        #expect(MetaTime.unixMs(c, zone: .fixed(seconds: 8 * 3600)) == MetaFixtures.ms("2019-01-05T07:22:15Z"))
        #expect(MetaTime.offset(inHeader: "Generated by X on Monday, February 9, 2026 at 9:15\u{202F}AM UTC+08:00") == 8 * 3600)
        #expect(MetaTime.offset(inHeader: "... UTC-05:30") == -(5 * 3600 + 30 * 60))
        #expect(MetaTime.offset(inHeader: "no zone here") == nil)
        #expect(MetaTime.generatedBy(inHeader: "Generated by Test Me on Monday, February 9, 2026") == "Test Me")
    }

    @Test func twelveHourEdgesAndInstagramMinutes() {
        #expect(MetaTime.parse("Mar 01, 2020 12:05 am") == MetaTime.Civil(y: 2020, mo: 3, d: 1, h: 0, mi: 5, s: 0))
        #expect(MetaTime.parse("Mar 01, 2020 12:30 pm") == MetaTime.Civil(y: 2020, mo: 3, d: 1, h: 12, mi: 30, s: 0))
        #expect(MetaTime.parse("Mar 01, 2020 11:59:59\u{202F}PM") == MetaTime.Civil(y: 2020, mo: 3, d: 1, h: 23, mi: 59, s: 59))
        #expect(MetaTime.parse("not a date") == nil)
        #expect(MetaTime.parse("Foo 01, 2020 1:00 am") == nil)
        // 2020 is a leap year
        let feb29 = MetaTime.parse("Feb 29, 2020 12:00:00 pm")!
        #expect(MetaTime.unixMs(feb29, zone: .fixed(seconds: 0)) == MetaFixtures.ms("2020-02-29T12:00:00Z"))
    }

    @Test func fixedOffsetIgnoresDaylightSavingNamedZoneFollowsIt() {
        // 2019-03-10 is the US spring-forward day. The same wall-clock time 24 hours apart:
        let a = MetaTime.parse("Mar 09, 2019 11:30 pm")!, b = MetaTime.parse("Mar 10, 2019 11:30 pm")!
        // fixed offset: exactly 24 h apart
        let fa = MetaTime.unixMs(a, zone: .fixed(seconds: -8 * 3600))!, fb = MetaTime.unixMs(b, zone: .fixed(seconds: -8 * 3600))!
        #expect(fb - fa == 24 * 3600 * 1000)
        // America/New_York: EST (-5) the first night, EDT (-4) the second
        let ny = "America/New_York"
        #expect(MetaTime.unixMs(a, zone: .named(ny)) == MetaFixtures.ms("2019-03-10T04:30:00Z"))
        #expect(MetaTime.unixMs(b, zone: .named(ny)) == MetaFixtures.ms("2019-03-11T03:30:00Z"))
        // and back in November: 2019-11-03 fall-back day, 1 h shorter/longer than the fixed difference
        let c = MetaTime.parse("Nov 02, 2019 11:30 pm")!, d = MetaTime.parse("Nov 03, 2019 11:30 pm")!
        #expect(MetaTime.unixMs(d, zone: .named(ny))! - MetaTime.unixMs(c, zone: .named(ny))! == 25 * 3600 * 1000)
        #expect(MetaTime.unixMs(a, zone: .named("No/Such_Zone")) == nil)
    }

    @Test func entitiesIncludingSurrogateReferencePairs() {
        func dec(_ s: String) -> String { Array(s.utf8).withUnsafeBufferPointer { HTMLEntities.decode($0) } }
        #expect(dec("it&#039;s &amp; &lt;b&gt; &quot;q&quot;") == "it's & <b> \"q\"")
        #expect(dec("&#55357;&#56832;") == "\u{1F600}")
        #expect(dec("&#x1F600;") == "\u{1F600}")
        #expect(dec("plain &unknown; stays & so") == "plain &unknown; stays & so")
        #expect(dec("no entities") == "no entities")
    }

    @Test func nameFoldingIsNFCAndCaseInsensitive() {
        let composed = "Jos\u{E9} Mu\u{F1}oz", decomposed = "Jose\u{301} MUN\u{303}OZ  "
        #expect(ServiceHandle.facebook(name: composed).normalized == ServiceHandle.facebook(name: decomposed).normalized)
        #expect(ServiceHandle.facebook(name: "A B").normalized != ServiceHandle.instagram(name: "A B").normalized)
        #expect(ServiceHandle.facebook(name: "A B", unique: "99").normalized == "fb:a b#99")
    }
}

