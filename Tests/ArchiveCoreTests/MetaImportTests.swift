    @Test func existingV4ArchiveMigratesInPlaceKeepingItsRows() throws {
        let dir = Fixtures.tempDir(); defer { try? FileManager.default.removeItem(at: dir) }
        let root = ArchiveRoot(url: dir.appendingPathComponent("root"))
        try root.createIfNeeded()
        do {
            let db = try Database(path: root.databaseURL.path)
            try db.exec("PRAGMA journal_mode = WAL")
            try Schema.migrate(db, upTo: 4)
            #expect(try db.userVersion() == 4)
            try db.exec("INSERT INTO source(id, kind, path, sha256, bytes, imported_at) VALUES (1,'android-xml','/x','abc',1,0)")
            try db.exec("INSERT INTO handle(id, raw, normalized, kind) VALUES (1,'+12125550111','+12125550111','phone')")
