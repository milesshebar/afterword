// Synthetic Meta-style exports only: invented names, invented text, tiny fake image bytes. The real exports are never
// copied into the repo; these fixtures reproduce only their DOM shape.

enum MetaFixtures {
    struct Msg {
        var sender: String?
        var text: String?
        var time: String
        var media: [String] = []                       // export-root-relative paths
        var reactions: [(String, String)] = []         // (emoji, name)
        var call: String?                              // "Duration: 12 seconds"
        var like = false
        var emojiInText = false                        // an emoji drawn as an inline image between words
        var rawReactions: [String] = []                // inner HTML of extra <li> rows
        var shareLink: String?
    }

    static func fbBlock(_ m: Msg) -> String {
        var s = "<div class=\"_a6-g\">"
        if let sd = m.sender { s += "<div class=\"_2ph_ _a6-h _a6-i\">\(sd)</div>" }
        s += "<div class=\"_2ph_ _a6-p\"><div><div></div>"
        s += "<div>\(m.text ?? "")\(m.emojiInText ? " <img alt=\"\" src=\"Https://static.example.invalid/rsrc/e2.png\" width=\"15\" height=\"15\" /> end" : "")\(m.like ? "<img alt=\"\" src=\"https://static.example.invalid/rsrc/like.gif?_nc=1\" width=\"15\" height=\"15\" />" : "")</div>"
        if let l = m.shareLink { s += "<div><div><div>Preview of the page</div><div><a target=\"_blank\" href=\"\(l)\">\(l)</a></div></div></div>" } else { s += "<div></div>" }
        s += "<div></div>"
        if let c = m.call { s += "<div><span class=\"_idm\">\(c)</span></div>" }
        for p in m.media { s += "<div><div><a target=\"_blank\" href=\"\(p)\"><img src=\"\(p)\" class=\"_a6_o _3-96\" /></a><div></div></div></div>" }
        if !m.reactions.isEmpty || !m.rawReactions.isEmpty { s += "<div><ul class=\"_a6-q\">" + m.reactions.map { "<li><span>\($0.0)\($0.1)</span></li>" }.joined() + m.rawReactions.map { "<li>\($0)</li>" }.joined() + "</ul></div>" }
        s += "<div>IP address: 192.0.2.1</div>"
        s += "</div></div><div class=\"_3-94 _a6-o\"><div class=\"_a72d\">\(m.time)</div></div></div>"
        return s
    }

    static func fbPage(title: String, generatedBy: String? = "Test Me", offset: String? = "+08:00", labelOnly: String? = nil, _ msgs: [Msg]) -> String {
        var s = "<html><head><meta http-equiv=\"content-type\" content=\"text/html; charset=utf-8\" /><base href=\"../../../../\"><style type=\"text/css\">._a6-g{color:red}</style><title>\(title)</title></head>"
        s += "<body class=\"_5vb_\"><div class=\"clearfix _ikh\"><div class=\"_4bl9\"><div class=\"_li\"><div class=\"_a705\"><div><div class=\"_3-8y _3-95 _a709\"><div class=\"_a70d\"><div class=\"_a70e\">\(title)</div>"
        if let g = generatedBy, let o = offset { s += "<div class=\"_aoaa\"><div>Generated by \(g) on Monday, February 9, 2026 at 9:15\u{202F}AM UTC\(o)</div></div>" }
        s += "</div></div></div><div class=\"_a706\" role=\"main\">"
        if let l = labelOnly { s += "<div class=\"_a6-g\"><div class=\"_2ph_ _a6-h\">\(l)</div></div>" }
        s += msgs.map(fbBlock).joined()
        s += "</div></div></div></div></div></body></html>"
        return s
    }

    static func igBlock(_ m: Msg) -> String {
        var s = "<div class=\"pam _3-95 _2ph- _a6-g uiBoxWhite noborder\">"
        if let sd = m.sender { s += "<div class=\"_3-95 _2pim _a6-h _a6-i\">\(sd)</div>" }
        s += "<div class=\"_3-95 _a6-p\"><div><div></div><div>\(m.text ?? "")</div>"
        if let l = m.shareLink { s += "<div><div><a target=\"_blank\" href=\"\(l)\">\(l)</a></div></div>" } else { s += "<div></div>" }
        s += "<div></div>"
        for p in m.media { s += "<div><div><a target=\"_blank\" href=\"\(p)\"><img src=\"\(p)\" class=\"_a6_o _3-96\" /></a><div></div></div></div>" }
        if !m.reactions.isEmpty { s += "<div><ul class=\"_a6-q\">" + m.reactions.map { "<li><span>\($0.0)<span>\($0.1)</span></span></li>" }.joined() + "</ul></div>" }
        s += "</div></div><div class=\"_3-94 _a6-o\">\(m.time)</div></div>"
        return s
    }

    static func igPage(title: String, extra: String = "", _ msgs: [Msg]) -> String {
        var s = "<html><head><base href=\"../../../../\"><title>\(title)</title></head><body><div class=\"clearfix _ikh\"><div class=\"_4bl9\"><div class=\"_li\">"
        s += "<div><table><tr><td><img src=\"files/Instagram-Logo.png\" height=\"28\" alt=\"Instagram\" /></td></tr></table></div>"
        s += "<div class=\"_a705\"><div><div class=\"_3-8y _3-95 _a70a\"><div class=\"_a70d\"><div class=\"_a70e\">\(title)</div></div></div></div><div class=\"_a706\" role=\"main\">"
        s += extra + msgs.map(igBlock).joined()
        s += "</div></div></div></div></div></body></html>"
        return s
    }

    /// Writes `<root>/<activity>/messages/<category>/<folder>/message_<n>.html` for each page, plus media files.
    @discardableResult
    static func writeThread(root: URL, activity: String, category: String = "inbox", folder: String, pages: [String], media: [String: [UInt8]] = [:]) -> URL {
        let dir = root.appendingPathComponent("\(activity)/messages/\(category)/\(folder)")
        try! FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        for (i, p) in pages.enumerated() { try! p.write(to: dir.appendingPathComponent("message_\(i + 1).html"), atomically: true, encoding: .utf8) }
        for (rel, bytes) in media {
            let u = root.appendingPathComponent(rel)
            try! FileManager.default.createDirectory(at: u.deletingLastPathComponent(), withIntermediateDirectories: true)
            try! Data(bytes).write(to: u)
        }
        return dir
    }

    static func ms(_ iso: String) -> Int64 { Int64(ISO8601DateFormatter().date(from: iso)!.timeIntervalSince1970) * 1000 }
}

private func q(_ db: Database, _ sql: String) throws -> Int64 { try db.scalarInt(sql) }
private func qs(_ db: Database, _ sql: String) throws -> String? { try db.scalarString(sql) }

