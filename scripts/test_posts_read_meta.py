class Facebook2025Pairing(unittest.TestCase):
    """The 2025 export prints one post in two lists; pairs are one to one."""

    def test_pairs(self):
        d = tempfile.mkdtemp()
        a = "your_facebook_activity/"
        bday = '<div><div class="_2pin"><div>Happy birthday!!</div></div></div>'
        yours = [fb_block("Casey Keeper wrote on Ann Bee&#039;s timeline.", bday, "Jun 02, 2011 1:48:42 am"),
                 fb_block("Casey Keeper wrote on Bo Sea&#039;s timeline.", bday, "Jun 02, 2011 1:48:42 am"),
                 fb_block(None, '<div><div class="_2pin"><div>an invented group post</div></div></div>', "Jan 2, 2014 1:00:00 pm")]
        others = [table_block([("Message", "Happy birthday!!")], "Jun 02, 2011 1:48:42 am"), table_block([("Message", "Happy birthday!!")], "Jun 02, 2011 1:48:42 am")]
        groups = [fb_block("Casey Keeper posted in Film Club.", '<div><div class="_2pin"><div>an invented group post</div></div></div>', "Jan 2, 2014 1:00:01 pm"),
                  fb_block("Casey Keeper posted in Film Club.", '<div><div class="_2pin"><div>another invented group post</div></div></div>', "Mar 3, 2013 2:00:00 pm")]
        pic = "your_facebook_activity/posts/media/your_posts/1_n_4444444444.jpg"
        unc = ['<div class="_a6-g"><div class="_2ph_ _a6-p">' f'<a href="{pic}"><img src="{pic}" /></a><div class="_3-95">another invented group post</div></div>'
               '<div class="_3-94 _a6-o"><a href="https://www.facebook.com/dyi/l/?l=x"><div class="_a72d">Mar 3, 2013 2:00:08 pm</div></a></div></div>']
        write_tree(d, {a + "posts/your_posts__check_ins__photos_and_videos_1.html": page(yours),
                       a + "posts/posts_on_other_pages_and_profiles.html": page(others),
                       a + "groups/group_posts_and_comments.html": page(groups),
                       a + "posts/your_uncategorized_photos.html": page(unc),
                       a + "activity_you're_tagged_in/photos_and_videos_you're_tagged_in.html": page([TAGGED[1].replace("100000000000103", "4444444444")])})
        _, recs = pr.read_fb2025(d, None)
        posts = [r for r in recs if r["type"] == "post"]
        # two birthday posts (two timelines) in the same second: two posts, each printed in both lists, kept once each
        bd = [r for r in posts if r["body"] == "Happy birthday!!"]
        self.assertEqual(sorted(r["target"] for r in bd), ["Ann Bee", "Bo Sea"])
        reps = [r for r in recs if r.get("reason") == "repeat-in-export"]
        self.assertEqual(len(reps), 5)                                 # 2 birthday copies, the "your posts" copy, the photo, the tag
        # the group copy is kept (it names the group); the "your posts" copy one second earlier is its repeat
        sh = [r for r in posts if r["body"] == "an invented group post"]
        self.assertEqual([(r["kind"], r["target_text"]) for r in sh], [("group-post", "Film Club")])
        # the photo posted in the group is that group post's photo
        sw = [r for r in posts if r["body"] == "another invented group post"]
        self.assertEqual(len(sw), 1)
        self.assertEqual((sw[0]["kind"], sw[0]["external_id"]), ("group-post", "4444444444"))
        self.assertIn(pic, sw[0]["media"])
        # every repeat names a record that is a post (a chain photo -> group post is followed to the end)
        posts_rids = {r["rid"] for r in posts}
        self.assertTrue(all(r["same_as"] in posts_rids for r in reps))


